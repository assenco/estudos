let corSinal = 'verde';

switch (corSinal){
    case 'verde':
        console.log("Siga");
        break;

    case 'amarelo':
        console.log("Atenção");
        break;   

    case 'vermelho':
        console.log("Pare");
        break; 
    
    default:
        console.log("Cor invalida");
        break; 
}